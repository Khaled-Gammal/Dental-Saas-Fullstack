export type Key = keyof typeof dict;
export const t = (key: Key, lang: Lang) => dict[key][lang];
/** User-facing text for an API error: our own words for known codes, the server's text otherwise. */
export function errorText(code: string, fallback: string, lang: Lang): string {
  const k = `err_${code}`;
  return k in dict ? t(k as Key, lang) : fallback;
}
export const roleLabel = (role: string, lang: Lang) => (`role_${role}` in dict ? t(`role_${role}` as Key, lang) : role);
/** Reads a saved language safely (storage can be blocked or hold junk). */
export function savedLang(): Lang {
  try {
    const v = localStorage.getItem('lang');
    return v === 'en' ? 'en' : 'ar';
  } catch {
    return 'ar';
  }
}
