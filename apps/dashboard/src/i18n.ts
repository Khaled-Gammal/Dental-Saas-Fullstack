export type Key = keyof typeof dict;
/** Every text key, for the Arabic-only check (L10N-001). */
export const KEYS = Object.keys(dict) as Key[];
export const t = (key: Key, lang: Lang) => dict[key][lang];
/** For keys built from data (audit actions, field names): the translation if one exists, else `fallback`. */
export const tOr = (key: string, lang: Lang, fallback: string) => (key in dict ? dict[key as Key][lang] : fallback);
/**
 * User-facing text for an API error (L10N-003): our own words for the code, else Arabic for its HTTP status — never
 * the server's English `detail`, which is for developers. No status (the network failed) reads as a server error.
 */
export function errorText(code: string, status: number | undefined, lang: Lang): string {
  const k = `err_${code}`;
  if (k in dict) return t(k as Key, lang);
  const s = status === undefined || status >= 500 ? 500 : [400, 401, 403, 404, 409, 429].includes(status) ? status : 400;
  return t(`err_generic_${s}` as Key, lang);
}
