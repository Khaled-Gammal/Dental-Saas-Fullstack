export type Key = keyof typeof dict;
/** Every text key, for the Arabic-only check (L10N-001). */
export const KEYS = Object.keys(dict) as Key[];
/** The dashboard is Arabic only (L10N-001, L10N-008): one text per key. */
export const t = (key: Key): string => dict[key];
/** For keys built from data (audit actions, field names): the text if one exists, else `fallback`. */
export const tOr = (key: string, fallback: string): string => (key in dict ? dict[key as Key] : fallback);
/**
 * User-facing text for an API error (L10N-003): our own words for the code, else Arabic for its HTTP status — never
 * the server's English `detail`, which is for developers. No status (the network failed) reads as a server error.
 */
export function errorText(code: string, status: number | undefined): string {
  const k = `err_${code}`;
  if (k in dict) return t(k as Key);
  const st = status === undefined || status >= 500 ? 500 : [400, 401, 403, 404, 409, 429].includes(status) ? status : 400;
  return t(`err_generic_${st}` as Key);
}
/** A role by its own name (roles are the clinic's, H4); the Arabic label of its key when no name is at hand. */
export const roleLabel = (role: string, name?: string | null): string => name || (`role_${role}` in dict ? t(`role_${role}` as Key) : role);
/** "5 دقائق" but "20 دقيقة": Arabic counts 3–10 with the plural form. */
export const minutesLabel = (n: number): string => t(n >= 3 && n <= 10 ? 'minutesFew' : 'minutes');
/** Catalogue category label; an unknown category shows its code rather than breaking the picker. */
export const categoryLabel = (c: string): string => (`cat_${c}` in dict ? t(`cat_${c}` as Key) : c);
